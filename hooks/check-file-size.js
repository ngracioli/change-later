#!/usr/bin/env node
// PreToolUse gate for Read: blocks direct reads of large files, redirects to bulk-reader subagent.
const fs = require("fs");
const { readSummary, MAX_ADDITIONAL_CONTEXT } = require("./lib/cache");
const { resolveLimits } = require("./lib/limits");
const { looksGenerated, readHead } = require("./lib/generated");

let input = "";
process.stdin.on("data", (chunk) => (input += chunk));
process.stdin.on("end", () => {
  let payload;
  try {
    payload = JSON.parse(input);
  } catch {
    process.exit(0);
  }

  // PreToolUse fires for subagent tool calls too. Without this, bulk-reader's own
  // Read on the file it was dispatched to read gets denied by itself — a deny loop.
  // agent_type is plugin-prefixed ("<plugin-name>:bulk-reader"), confirmed empirically
  // by dumping the real hook payload — doc-derived "bulk-reader" exact match doesn't fire.
  if (payload?.agent_type?.split(":").pop() === "bulk-reader") process.exit(0);

  const filePath = payload?.tool_input?.file_path;
  if (!filePath) process.exit(0);

  const { lineLimit, byteLimit } = resolveLimits(filePath);

  // Paginated read (offset/limit) for a slice at or under the threshold is already cheap — let it through.
  const requestedLimit = Number(payload?.tool_input?.limit);
  if (Number.isFinite(requestedLimit) && requestedLimit > 0 && requestedLimit <= lineLimit) {
    process.exit(0);
  }

  // Explicit offset means the caller already knows where to look (e.g. after a bulk-reader
  // summary, or during an edit) — that's a targeted read, not a bulk one. Let it through
  // regardless of size, even if the requested limit is still above lineLimit.
  if ("offset" in (payload?.tool_input ?? {})) process.exit(0);

  let stat;
  try {
    stat = fs.statSync(filePath);
  } catch {
    process.exit(0);
  }

  // Cache hit: the file hasn't changed (same mtime+size) since bulk-reader last
  // summarized it — serve the summary directly, no delegation, no model call.
  const cached = readSummary(filePath, stat);
  if (cached) {
    const summary =
      cached.length > MAX_ADDITIONAL_CONTEXT
        ? `${cached.slice(0, MAX_ADDITIONAL_CONTEXT)}\n\n[cached summary truncated — file unchanged since last bulk-reader pass, but summary exceeds the ${MAX_ADDITIONAL_CONTEXT}-char inline budget]`
        : cached;
    console.log(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: `Do not read this file — it hasn't changed since the last bulk-reader pass. Here is the cached summary:\n\n${summary}`,
        },
      })
    );
    process.exit(0);
  }

  let reason;
  let generated = false;
  if (stat.size > byteLimit) {
    generated = looksGenerated(readHead(filePath));
    reason = generated
      ? generatedReason(`${Math.round(stat.size / 1024)}KB`)
      : `File is ${Math.round(stat.size / 1024)}KB (limit ${Math.round(byteLimit / 1024)}KB) — large in bytes even if short in lines (minified/JSON/CSV). To understand this file, invoke the Task tool with subagent_type: "bulk-reader" NOW — it's the first option, not the last. Do NOT reconstruct the content with repeated greps or searches: that pulls the file back into context and wastes tokens, which is exactly what delegation avoids. A targeted grep for ONE specific reference is fine; to map or summarize the file, delegate.`;
  } else {
    let content;
    try {
      content = fs.readFileSync(filePath, "utf8");
    } catch {
      process.exit(0);
    }
    const lineCount = content.split("\n").length;
    if (lineCount <= lineLimit) process.exit(0);
    generated = looksGenerated(content);
    reason = generated
      ? generatedReason(`${lineCount} lines`)
      : `File has ${lineCount} lines (limit ${lineLimit}). To understand this file, invoke the Task tool with subagent_type: "bulk-reader" NOW — it's the first option, not the last. Do NOT reconstruct the content with repeated greps or searches: that pulls the file back into context and wastes tokens, which is exactly what delegation avoids. A targeted grep for ONE specific reference is fine; to map or summarize the file, delegate.`;
  }

  // Deny via JSON on stdout, not exit code: exit 2 also blocks and is documented as
  // redundant here, but the doc guidance is to pick one contract per hook, and the
  // hook's entire value is in permissionDecisionReason (the delegation instruction) —
  // JSON+exit 0 is the narrower surface if the contract changes later.
  console.log(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason: reason,
      },
    })
  );
  process.exit(0);
});

function generatedReason(sizeDescription) {
  return `File is ${sizeDescription} and looks generated (@generated / DO NOT EDIT / Code generated by marker in the first lines). Generated files aren't meant to be understood, only searched inside — do NOT delegate to bulk-reader for this one, that's a wasted 10-30s delegation. Use a targeted Grep for the specific symbol/string you need instead.`;
}
